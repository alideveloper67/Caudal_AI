class EscenarioDef {
  const EscenarioDef({
    required this.clave,
    required this.nombre,
    required this.asset,
    required this.ancho,
    required this.alto,
    required this.efectos,
    this.epico = false,
    this.interaccion = 'chispa',
    this.coloresInteraccion = const ['#FFFFFF'],
    this.vineta = 70,
  });

  final String clave;
  final String nombre;

  /// Nombre del archivo dentro de assets/escenarios/.
  final String asset;
  final int ancho;
  final int alto;
  final List<Efecto> Function() efectos;

  /// Épicos (ippo, goku): sacudida corta y destello con los golpes de graves o un toque.
