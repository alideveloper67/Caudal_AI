  /// Tipo de partícula de la interacción (petalo, estrella, corazon, flor, chispa...).
  final String interaccion;
  final List<String> coloresInteraccion;

  /// Oscurecimiento de los bordes (0..255, alfa del negro).
  final int vineta;
}

